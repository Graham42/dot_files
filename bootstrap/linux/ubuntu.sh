#!/usr/bin/env bash

# Command-line setup for a dev machine: apt packages, rust tools, etc. No
# desktop packages, GUI apps or desktop settings - ubuntu-desktop.sh and
# mint-desktop.sh do that, and each runs this script itself, so don't run it
# first. On its own it's for a headless machine.
#
# Ubuntu is in the name, but Mint runs it too (mint-desktop.sh). Nothing here
# is release- or desktop-specific.

set -e -u -o pipefail

function log {
  echo -e "\033[34m$*\033[0m"
}

script_dir="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=./apt-repo-common.sh
source "$script_dir/apt-repo-common.sh"

log "Updating, upgrading and cleaning up apt packages..."
sudo apt update && sudo apt upgrade -y
sudo apt autoremove -y
log "Packages up to date, unused ones removed"

log "Adding GitHub CLI apt repo..."
apt_source_exists github-cli || add_apt_key_repo \
  https://cli.github.com/packages/githubcli-archive-keyring.gpg \
  /etc/apt/keyrings/githubcli-archive-keyring.gpg \
  github-cli \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/githubcli-archive-keyring.gpg] https://cli.github.com/packages stable main"
sudo apt update
log "GitHub CLI apt repo added"

log "Installing packages..."
packages=(
  # version control system
  git
  # GitHub CLI
  gh
  # c compiler + linker, required for compiling rust crates via cargo
  build-essential
  # text editor, gtk version includes +clipboard support for copying to system clipboard
  vim-gtk3
  # vim fork with more usability improvements
  neovim
  # json manipulation tool
  jq
  # terminal multiplexer, easy management of multiple terminal panes in single window
  tmux
  # tool for visualizing folder structures
  tree
  # utility for grabbing to clipboard
  xclip
  curl
  # rust-based grep replacement (rg)
  ripgrep
  # shell script linting tool
  shellcheck
)

sudo apt-get install -y "${packages[@]}"
log "Packages installed"

# Rust toolchain, for the cargo installs below.
curl https://sh.rustup.rs -sSf | sh -s -- -y
# shellcheck disable=SC1091 # generated by rustup at install time, not in the repo
source "$HOME/.cargo/env"

log "Installing rust-based CLI tools..."
# --locked on every line: build each crate against the Cargo.lock its authors
# committed, so a new release of some transitive dependency can't break the
# install. The trade is that dependency fixes only arrive when the crate
# itself is released again.

# gitconfig.sh builds bat's theme cache and delta renders diffs with its own
# embedded bat, so the two have to agree on that cache's format. apt's bat is a
# different version, and the mismatch breaks syntax highlighting in git diffs,
# so we need to install it with cargo
cargo install --locked bat        # syntax-highlighted file viewer
cargo install --locked sd         # sed replacement
cargo install --locked fd-find    # find replacement (fd)
cargo install --locked git-delta  # better git diffs (delta)
cargo install --locked hyperfine  # benchmarking tool
cargo install --locked zoxide     # smarter cd
cargo install --locked starship   # shell prompt
log "Rust tools installed"

log "Installing Node.js (fnm) and bun..."
"$(dirname "$0")/node.sh"
log "Node.js and bun installed"

log "Command-line tools installed. Restart your shell (or 'source ~/.bashrc') to get them on PATH."
